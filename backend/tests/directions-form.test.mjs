import assert from 'node:assert/strict';
import fs from 'node:fs';
import {parseHTML} from 'linkedom';
import {parseMarsCoordinates} from '../public/js/directions-model.js';
assert.deepEqual(parseMarsCoordinates('45.638, 188.625'),[45.638,-171.375]);
assert.equal(parseMarsCoordinates('91, 20'),null);
assert.equal(parseMarsCoordinates('45, 400'),null);
assert.equal(parseMarsCoordinates('not a place'),null);
const {document,window}=parseHTML(fs.readFileSync(new URL('../public/index.html',import.meta.url),'utf8'));
globalThis.document=document;globalThis.window=window;
window.HTMLElement.prototype.scrollIntoView=function(){};
const nativeFetch=globalThis.fetch;
const origin=process.env.APP_TEST_ORIGIN||'https://127.0.0.1:8789';
globalThis.fetch=(url,options)=>nativeFetch(new URL(url,origin),options);
const api=await import('../public/js/api.js');
await api.connectBackend();
const {REGIONS}=await import('../public/js/config.js');
const {createDirectionsPanel}=await import('../public/js/directions-panel.js');
const state={regionId:'arcadia',pointA:REGIONS.arcadia.pointA,pointB:REGIONS.arcadia.pointB};
const captures=[];
let panel;
panel=createDirectionsPanel({getState:()=>state,onDraft(){},onFit(){},onSubmit(from,to){captures.push({from,to});state.pointA=from;state.pointB=to;panel.sync(state);}});
panel.sync(state);
const inputA=document.getElementById('from-input'),inputB=document.getElementById('destination-input');
const type=(input,value)=>{input.value=value;input.dispatchEvent(new window.Event('input'));};
const submit=()=>document.getElementById('directions-form').dispatchEvent(new window.Event('submit',{cancelable:true}));
type(inputA,state.pointA.coords[0]+', '+(state.pointA.coords[1]+360));
type(inputB,state.pointB.coords.join(', '));
submit();assert.equal(captures.length,1);
assert.ok(Math.abs(captures[0].from.coords[1]-REGIONS.arcadia.pointA.coords[1])<1e-10);
panel.setBusy(true);assert.equal(document.getElementById('get-directions').disabled,true);
const route=await api.computeRouteAPI('arcadia',captures[0].from,captures[0].to,3.5);
assert.equal(route.available,true,route.message);panel.setRoute(route);
assert.equal(document.getElementById('get-directions').disabled,false);
assert.equal(document.getElementById('directions-summary').hidden,false);
assert.ok(document.getElementById('turn-list').children.length>0);
panel.swap();assert.equal(captures.length,2);assert.deepEqual(captures[1].from.coords,captures[0].to.coords);
type(inputB,'latitude is missing');submit();assert.equal(captures.length,2);
assert.equal(inputB.getAttribute('aria-invalid'),'true');assert.match(document.getElementById('directions-error').textContent,/Destination/);
type(inputA,REGIONS.arcadia.pointB.name.slice(0,5));
const suggestions=document.getElementById('from-suggestions');assert.ok(suggestions.children.length>0);
const key=new window.Event('keydown',{cancelable:true});key.key='ArrowDown';inputA.dispatchEvent(key);
assert.equal(suggestions.children[0].getAttribute('aria-selected'),'true');
const enter=new window.Event('keydown',{cancelable:true});enter.key='Enter';inputA.dispatchEvent(enter);
assert.equal(suggestions.hidden,true);assert.equal(captures.length,2,'Choosing a suggestion does not submit incomplete endpoints');
console.log('PASS: real directions form, keyboard suggestions, east-longitude coordinates, validation, swapping, live API routing, route summary and direction steps.');

state.regionId='jezero';state.pointA=REGIONS.jezero.pointA;state.pointB=REGIONS.jezero.pointB;panel.sync(state);
document.getElementById('use-measured-route').click();
const chosen=captures.at(-1),jezero=await api.computeRouteAPI('jezero',chosen.from,chosen.to,3.5);
assert.equal(jezero.available,true,jezero.message);assert.equal(jezero.raw.data_version,'jezero-hirise-v1');assert.equal(jezero.resolution_m,20);panel.setRoute(jezero);
assert.equal(document.getElementById('directions-summary').hidden,false);assert.ok(jezero.routePoints.length>10);
const outside=await api.computeRouteAPI('jezero',chosen.from,{name:'Bright Angel',coords:[18.485,77.362]},3.5);assert.equal(outside.available,false);assert.match(outside.message,/loaded Jezero terrain/);
console.log('PASS: Get directions and measured-route shortcut work in Jezero; outside-coverage locations return a clear explanation.');

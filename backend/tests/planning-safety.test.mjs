import assert from 'node:assert/strict';
import {conditionFor,originalHazards,demoZoneAt,demoRing,marsDistance,metersToLatLng,savePlanningSettings,planningSettings} from '../public/js/planning-safety.js';
const settings={maxSlope:5,demoHazards:false};
assert.equal(conditionFor({slopeDeg:null},[45.638,-171.375],'arcadia',settings).kind,'unknown');
assert.equal(conditionFor({slopeDeg:2.79},[45.638,-171.375],'arcadia',settings).kind,'within');
assert.equal(conditionFor({slopeDeg:2.8},[45.638,-171.375],'arcadia',settings).kind,'caution');
assert.equal(conditionFor({slopeDeg:5},[45.638,-171.375],'arcadia',settings).kind,'caution');
assert.equal(conditionFor({slopeDeg:5.01},[45.638,-171.375],'arcadia',settings).kind,'blocked');
assert.equal(conditionFor({slopeDeg:4},[45.638,-171.375],'arcadia',{maxSlope:3,demoHazards:false}).kind,'blocked');
const original=originalHazards('arcadia');assert.equal(original.length,3);
const hazard=original[0],coordinate=[hazard.lat,hazard.lng];
assert.equal(demoZoneAt('arcadia',coordinate).id,'crater_east');
assert.equal(demoZoneAt('arcadia',[45.638,-171.375]),null);
assert.equal(conditionFor({slopeDeg:null},coordinate,'arcadia',settings).kind,'unknown');
assert.equal(conditionFor({slopeDeg:null},coordinate,'arcadia',{...settings,demoHazards:true}).kind,'demo');
for(const point of demoRing(hazard))assert.ok(Math.abs(marsDistance(coordinate,point)-hazard.radius)<.001,'Scenario radius uses Mars meters, not Earth meters');
assert.deepEqual(metersToLatLng([0,0]),[45.638,-171.375]);
savePlanningSettings({maxSlope:999});assert.equal(planningSettings.maxSlope,30);
savePlanningSettings({maxSlope:5});assert.equal(planningSettings.maxSlope,5);
console.log('PASS: original hazard zones, Mars distances, missing-data conditions, 2.8/5 degree boundaries, user slope limits and explicit demo labeling.');
